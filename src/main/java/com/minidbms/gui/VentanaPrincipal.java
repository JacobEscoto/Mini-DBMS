    private void abrirArchivoMItemActionPerformed(java.awt.event.ActionEvent evt) { // GEN-FIRST:event_abrirArchivoMItemActionPerformed
        if (ruta == null) {
            JFileChooser selector = new JFileChooser();
            int seleccionado = selector.showOpenDialog(null);
            if (seleccionado == JFileChooser.APPROVE_OPTION) {
                File file = selector.getSelectedFile();
                ruta = file.getAbsolutePath();
                try {
                    FileReader fr = new FileReader(file);
                    BufferedReader br = new BufferedReader(fr);
                    metadata = new Metadata(ruta);
                    metadata.leer(br);
                    br.close();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(null, "Error al abrir el archivo: " + e);
                    ruta = null;
                    metadata = null;
                }
            }
        }
    } // GEN-LAST:event_abrirArchivoMItemActionPerformed

