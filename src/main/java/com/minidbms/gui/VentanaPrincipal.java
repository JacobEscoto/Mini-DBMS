    private void abrirArchivoMItemMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_abrirArchivoMItemMouseClicked
        JFileChooser selector = new JFileChooser();
        int seleccionado = selector.showOpenDialog(null);
        if (ruta != null) {
            if (seleccionado == JFileChooser.APPROVE_OPTION) {
                File file = selector.getSelectedFile();
                ruta = file.getAbsolutePath();
                File Archivo = new File(ruta);
                try {
                    FileReader fr = new FileReader(Archivo);
                    BufferedReader br = new BufferedReader(fr);
                    
                    
                    
                    br.close();
                } catch (Exception e) {
                }

            }
        }
    }//GEN-LAST:event_abrirArchivoMItemMouseClicked

