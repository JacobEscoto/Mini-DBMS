    private void modificarCampoBtnMouseClicked(
            java.awt.event.MouseEvent evt) { // GEN-FIRST:event_modificarCampoBtnMouseClicked
        int fila = tablaCampos.getSelectedRow();
        if (fila == -1) {
            error("Seleccionar un campo en la tabla para modificar");
            return;
        }
        int id = (int) tablaCampos.getValueAt(fila, 0);
        Campo campo = controlador.obtenerMetadata().buscarCampoPorId(id);
        String[] opciones = {"Nombre", "Tipo", "Longitud"};
        String opcion =
                (String)
                        JOptionPane.showInputDialog(
                                null,
                                "Seleccione qué desea modificar:",
                                "Modificar campo",
                                JOptionPane.QUESTION_MESSAGE,
                                null,
                                opciones,
                                opciones[0]);
        if (opcion == null) {
        return;
    }
        switch (opcion) {
            case "Nombre":
                String nombre =
                        JOptionPane.showInputDialog(
                                null, "Ingrese el nuevo nombre:", campo.obtenerNombre());
                if (nombre != null && !nombre.trim().isEmpty()) {
                    controlador.obtenerMetadata().renombrarCampo(id, nombre);
                }
                break;
            case "Tipo":
                TipoCampo tipo =
                        (TipoCampo)
                                JOptionPane.showInputDialog(
                                        null,
                                        "Seleccione el nuevo tipo:",
                                        "Modificar tipo",
                                        JOptionPane.QUESTION_MESSAGE,
                                        null,
                                        TipoCampo.values(),
                                        campo.obtenerTipo());
                if (tipo == null) {
                return;
            }
                if (tipo == TipoCampo.TEXTO && campo.obtenerTipo() != TipoCampo.TEXTO) {
                    String tamano =
                            JOptionPane.showInputDialog(null, "Ingrese el tamaño para su texto:")
                                    .trim();
                    if (tamano.isBlank()) {
                        error("Ingrese un numero del tamaño para modificar");
                        return;
                    }
                    try {
                        int tam = Integer.parseInt(tamano);
                        controlador.obtenerMetadata().cambiarTipoCampo(id, tipo, tam);
                        actualizarTablaCampos();
                        return;
                    } catch (Exception e) {
                        error("Ingrese numero");
                        return;
                    }
                }
                controlador
                        .obtenerMetadata()
                        .cambiarTipoCampo(id, tipo, campo.obtenerLongitudMaxima());
                if (tipo == null) {
                    return;
                }
                controlador
                        .obtenerMetadata()
                        .cambiarTipoCampo(id, tipo, campo.obtenerLongitudMaxima());
                break;
            case "Longitud":
                if (campo.obtenerTipo() != TipoCampo.TEXTO) {
                    error("Solo texto tiene tamaño maxíma");
                    return;
                }
                String tamano =
                        JOptionPane.showInputDialog(null, "Ingrese el tamaño para su texto:")
                                .trim();
                if (tamano.isBlank()) {
                    error("Ingrese un numero del tamaño para modificar");
                    return;
                }
                try {
                    int tam = Integer.parseInt(tamano);
                    controlador.obtenerMetadata().cambiarTipoCampo(id, campo.obtenerTipo(), tam);
                    actualizarTablaCampos();
                    return;
                } catch (Exception e) {
                    error("Ingrese numero");
                    return;
                }
        }
        actualizarTablaCampos();
    } // GEN-LAST:event_modificarCampoBtnMouseClicked

    private void borrarCampoBtnMouseClicked(
            java.awt.event.MouseEvent evt) { // GEN-FIRST:event_borrarCampoBtnMouseClicked
        int fila = tablaCampos.getSelectedRow();
        if (fila == -1) {
            error("Seleccionar un campo en la tabla para borrar");
            return;
        }
        int id = (int) tablaCampos.getValueAt(fila, 0);
        String nombre = (String) tablaCampos.getValueAt(fila, 1);

        int borrarOk =
                JOptionPane.showConfirmDialog(
                        this,
                        "Se borrará el campo \""
                                + nombre
                                + "\". Esta acción no se puede deshacer. ¿Confirma?",
                        "Confirmación de eliminación",
                        JOptionPane.YES_NO_OPTION,
                        JOptionPane.WARNING_MESSAGE);
        if (borrarOk != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            controlador.borrarCampo(id);
            actualizarTablaCampos();
            info("Campo borrado correctamente");
        } catch (CampoInexistenteException | ArchivoInvalidoException ex) {
            error(ex.getMessage());
        } catch (IllegalStateException ex) {
            error("No se puede borrar: " + ex.getMessage());
        }
    } // GEN-LAST:event_borrarCampoBtnMouseClicked

